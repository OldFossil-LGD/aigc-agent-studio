"""Creative-intent question bank v2 — eight dimensions plus production gates.

The bank is **data, not conversation**: the session engine picks one question at
a time from it, and the Agent never improvises a questionnaire. Each question
carries everything the engine needs to decide *whether* it is worth asking:

* `requires` — dependency edges (never ask downstream of an unheard answer);
* `when` — answer-dependent branches (情感反转 → 关系轴; 烧脑推理 → 线索公平);
* `stops` — which delivery stops the question belongs to (prompt / film /
  generation), so a prompt-only job never sees film-stage questions;
* `blocking_for` — which stops cannot be gated without it;
* `priority` — the six relative factors from the spec (impact, rework,
  uncertainty, relevance, friction, defaultable). Scores are library-set
  relative weights, **not calibrated confidence**;
* `cic` — where the answer lands in the Creative Intent Contract.

Questions prefixed `G` are the production gates (delivery, assets, continuity,
budget, ignition, reverse contract). Questions prefixed `I` are the creative
intent dimensions (goal, story, structure, visual, people, constraints,
authority, delivery specs).
"""

