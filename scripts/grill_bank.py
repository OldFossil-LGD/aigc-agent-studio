QUESTION_INDEX = {question["id"]: question for question in QUESTION_BANK}


def priority_weights(question: dict[str, Any]) -> dict[str, float]:
    return dict(question["priority"])


def priority_score(question: dict[str, Any], content_type: str | None = None) -> float:
    """Spec §4.3 relative score. Never presented to users as calibrated confidence."""

    weights = question["priority"]
    score = (weights["impact"] + weights["rework"] + weights["uncertainty"]
             + weights["relevance"] - weights["friction"] - weights["defaultable"])
    if content_type:
        score += CONTENT_TYPE_BIAS.get(content_type, {}).get(question["dimension"], 0)
    return score


def cic_mappings(question: dict[str, Any]) -> list[dict[str, str]]:
    """Where an answer lands in the Creative Intent Contract."""

    raw = question.get("cic")
    if not raw:
        return []
    if isinstance(raw, str):
        return [{"path": raw}]
    return [dict(item) for item in raw]


def answer_errors(question: dict[str, Any], answer: Any) -> list[str]:
    """Validate an answer against the question's declared shape."""

    kind = question["kind"]
    if kind == "text":
        return [] if isinstance(answer, str) and answer.strip() else ["answer must be a non-empty string"]
    if kind == "number":
        if isinstance(answer, bool) or not isinstance(answer, (int, float)) or answer <= 0:
            return ["answer must be a positive number"]
        return []
    if kind == "ratio":
        import re as _re
        pattern = _re.compile(r"^\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?\s*$")
        return [] if isinstance(answer, str) and pattern.match(answer) else ["answer must look like 'W:H' (16:9, 9:16, 2.39:1)"]
    if kind == "text_list":
        # An empty list is an honest "none" (国: 「没有就写『无』」)—not a missing answer.
        if not isinstance(answer, list):
            return ["answer must be a list of strings"]
        return [] if all(isinstance(item, str) and item.strip() for item in answer) else ["answer items must be non-empty strings"]
    if kind == "choice":
        return [] if answer in question["choices"] else ["answer %r is not one of %s" % (answer, ", ".join(question["choices"]))]
    if kind == "object":
        if not isinstance(answer, dict):
            return ["answer must be an object"]
        fields = question["fields"]
        unknown = sorted(set(answer) - set(fields))
        if unknown:
            return ["answer has unmapped fields: %s" % ", ".join(unknown)]
        errors = []
        for name, spec in fields.items():
            if name not in answer:
                errors.append("answer is missing field %s" % name)
                continue
            value = answer[name]
            if spec["type"] == "choice" and value not in spec["choices"]:
                errors.append("field %s=%r is not one of %s" % (name, value, ", ".join(spec["choices"])))
            if spec["type"] == "text" and (not isinstance(value, str) or not value.strip()):
                errors.append("field %s must be a non-empty string" % name)
            if spec["type"] == "text_list":
                if not isinstance(value, list) or not value or any(not isinstance(item, str) or not item.strip() for item in value):
                    errors.append("field %s must be a non-empty list of strings" % name)
        return errors
    return ["unknown answer kind %r" % kind]
